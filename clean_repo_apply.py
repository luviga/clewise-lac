"""
Apply deprecation moves based on a report from clean_repo_identify.py.

This is the half of the audit that actually touches your filesystem. It reads
the CSV report, takes everything classified as `move_safe` or `move_candidate`
(depending on --mode), and relocates those files into

    _deprecate/<timestamp>/<original_relative_path>

The destination tree mirrors the source tree exactly, but only the moved
files appear in it. Nothing is copied; everything is moved with shutil.move,
so the originals are gone after a successful run. Restore is a `mv` away
because the tree is preserved.

The report CSV is read-only to this script. The destination tree itself is
the record of what moved — no need to mutate the report. This avoids file-
lock fights with Dropbox / OneDrive / iCloud / Excel.

Usage:

    py clean_repo_apply.py --dry-run                    # preview only
    py clean_repo_apply.py --mode safe                  # move cache/temp
    py clean_repo_apply.py --mode candidates            # also move flagged stale files
    py clean_repo_apply.py --mode candidates --yes      # skip confirmation prompt

Defaults are deliberately cautious: dry-run + interactive confirmation.

Safety nets:
  1. NEVER_MOVE — a hardcoded list of files this script will refuse to move
     no matter what the report says. If any of these appear in the report
     with action=move_*, the script aborts before touching anything. This
     protects you from running a stale report (e.g. one generated by the
     pre-patch classifier that mislabels v14 or DR's TESTEOS runner).
  2. Existence check — files that don't exist on disk are silently skipped
     (no traceback, just a count in the summary).
  3. Path collision — if a target already exists under _deprecate/<ts>/, an
     incrementing suffix is appended.
"""

from __future__ import annotations

import argparse
import csv
import shutil
import sys
from datetime import datetime
from pathlib import Path


REPORT_DEFAULT = "deprecation_candidates_report.csv"
DEPRECATE_DIR = "_deprecate"


# Hardcoded safety net. These files MUST NOT be moved regardless of what the
# report says. If the report flags any of them for move, this script will
# refuse to run and tell the user to regenerate the report with the patched
# classifier.
NEVER_MOVE = {
    # Current stage scripts
    "stage3_target_shares_v14.py",
    "stage4_generate_opt.py",
    "stage5_bau_constrained_v7.py",

    # Audit / handover tooling (current names)
    "clean_repo_identify.py",
    "clean_repo_apply.py",
    # Tolerate prior names too, in case an older copy is still around
    "identify_deprecation_candidates_v2.py",
    "apply_deprecation_moves.py",
    "cleanup_audit_models_lac_4.py",
    "STAGE_SCRIPTS_EXPLAINED.md",
    "HANDOVER_PROMPT_ENERGY_ADJUSTMENTS.md",

    # Active scenario controller
    "CONTROLLER_NEW_SCENARIOS.xlsx",
}

# Filenames (without path) that LOOK stale because their substring matches
# a marker but are actually active. If the report flags any of these, abort.
NEVER_MOVE_BY_FILENAME = {
    "B1_Base_Scenarios_Adj_Parallel_ADJ_TESTEOS.py",  # DR's production runner
}


def read_report(report_path: Path) -> list[dict[str, str]]:
    with report_path.open("r", newline="", encoding="utf-8") as handle:
        reader = csv.DictReader(handle)
        rows = list(reader)
    if not rows:
        raise SystemExit(f"Report {report_path} is empty.")
    return rows


def actions_for_mode(mode: str) -> set[str]:
    if mode == "safe":
        return {"move_safe"}
    if mode == "candidates":
        return {"move_safe", "move_candidate"}
    if mode == "all":
        return {"move_safe", "move_candidate"}
    raise SystemExit(f"Unknown --mode: {mode!r}")


def filename_of(rel_path: str) -> str:
    return Path(rel_path).name


def check_safety_net(rows: list[dict[str, str]], allowed_actions: set[str]) -> None:
    """Refuse to run if the report flags any NEVER_MOVE file for relocation."""
    violations: list[str] = []
    for row in rows:
        if row["action"] not in allowed_actions:
            continue
        path = row["path"]
        name = filename_of(path)
        if name in NEVER_MOVE or name in NEVER_MOVE_BY_FILENAME:
            violations.append(f"  - {path}  (flagged as {row['action']}, category={row['category']})")

    if violations:
        print("REFUSING TO RUN.", file=sys.stderr)
        print("The report flags files that are on the NEVER_MOVE safety list:", file=sys.stderr)
        for v in violations:
            print(v, file=sys.stderr)
        print("", file=sys.stderr)
        print("This usually means the report was generated by the pre-patch", file=sys.stderr)
        print("classifier. Re-run clean_repo_identify.py to regenerate", file=sys.stderr)
        print("the report, then try again.", file=sys.stderr)
        raise SystemExit(2)


def choose_move_path(dest_root: Path, rel_path: Path) -> Path:
    """Pick a destination, appending an incrementing suffix on collision."""
    target = dest_root / rel_path
    if not target.exists():
        return target

    stem = target.stem
    suffix = target.suffix
    parent = target.parent
    counter = 1
    while True:
        candidate = parent / f"{stem}__{counter}{suffix}"
        if not candidate.exists():
            return candidate
        counter += 1


def plan_moves(
    rows: list[dict[str, str]], allowed_actions: set[str], root: Path
) -> list[tuple[dict[str, str], Path]]:
    """Return [(row, source_path)] for rows we'd actually move (file exists)."""
    plan: list[tuple[dict[str, str], Path]] = []
    for row in rows:
        if row["action"] not in allowed_actions:
            continue
        source = root / Path(row["path"])
        if not source.exists():
            continue
        plan.append((row, source))
    return plan


def print_plan_summary(plan: list[tuple[dict[str, str], Path]], rows: list[dict[str, str]], allowed_actions: set[str]) -> None:
    """Show what's about to happen, broken down by action and category."""
    by_action_cat: dict[tuple[str, str], list[int]] = {}
    skipped = 0

    for row in rows:
        if row["action"] not in allowed_actions:
            continue
        source_exists = (Path(row["path"]).is_absolute() or True)  # placeholder; real check below
        # The real existence check happens in plan_moves; for the missing count:
    planned_paths = {str(p) for _, p in plan}

    for row, source in plan:
        key = (row["action"], row["category"])
        by_action_cat.setdefault(key, []).append(int(row.get("size_bytes") or 0))

    # Count rows in allowed actions that are NOT in the plan (= missing on disk)
    for row in rows:
        if row["action"] not in allowed_actions:
            continue
        full = str((Path.cwd() / row["path"]).resolve())  # rough; fine for reporting
        if not (Path(row["path"]).exists() or Path(full).exists()):
            skipped += 1

    print()
    print("Move plan")
    print("---------")
    if not by_action_cat:
        print("  (nothing to move)")
        return

    total_files = 0
    total_bytes = 0
    for (action, category), sizes in sorted(by_action_cat.items()):
        n = len(sizes)
        mb = sum(sizes) / (1024 * 1024)
        total_files += n
        total_bytes += sum(sizes)
        print(f"  {action:16}  {category:36}  {n:5d} files  {mb:8.2f} MB")
    print(f"  {'TOTAL':16}  {'':36}  {total_files:5d} files  {total_bytes/(1024*1024):8.2f} MB")
    if skipped:
        print(f"  (skipping {skipped} rows whose source file no longer exists)")


def confirm(prompt: str) -> bool:
    try:
        reply = input(prompt + " [y/N]: ").strip().lower()
    except EOFError:
        return False
    return reply in {"y", "yes"}


def execute_moves(
    plan: list[tuple[dict[str, str], Path]], dest_root: Path, root: Path
) -> tuple[int, int]:
    """Move files. Returns (moved_count, total_bytes_moved)."""
    moved = 0
    total_bytes = 0
    for row, source in plan:
        rel = Path(row["path"])
        target = choose_move_path(dest_root, rel)
        target.parent.mkdir(parents=True, exist_ok=True)
        try:
            shutil.move(str(source), str(target))
        except OSError as exc:
            print(f"  ! failed: {row['path']}  ({exc})", file=sys.stderr)
            continue
        moved += 1
        total_bytes += int(row.get("size_bytes") or 0)
    return moved, total_bytes


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument(
        "--root",
        default=".",
        help="Workspace root. Must match the root used to generate the report. Default: current directory.",
    )
    parser.add_argument(
        "--report",
        default=REPORT_DEFAULT,
        help=f"CSV report to read. Default: {REPORT_DEFAULT}",
    )
    parser.add_argument(
        "--mode",
        choices=["safe", "candidates", "all"],
        default="safe",
        help="What to move. 'safe' = pycache/temp/lock files only. 'candidates' = also stale workbooks/scripts. Default: safe.",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Print what would be moved without touching anything.",
    )
    parser.add_argument(
        "--yes",
        action="store_true",
        help="Skip the interactive confirmation prompt.",
    )
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    root = Path(args.root).resolve()
    report_path = Path(args.report)
    if not report_path.is_absolute():
        report_path = root / report_path

    if not report_path.exists():
        print(f"Report not found: {report_path}", file=sys.stderr)
        print("Run clean_repo_identify.py first.", file=sys.stderr)
        return 1

    rows = read_report(report_path)
    allowed_actions = actions_for_mode(args.mode)

    # Safety net BEFORE we do anything destructive.
    check_safety_net(rows, allowed_actions)

    plan = plan_moves(rows, allowed_actions, root)
    print(f"Workspace root: {root}")
    print(f"Report:         {report_path}")
    print(f"Mode:           {args.mode}  (actions: {sorted(allowed_actions)})")
    print_plan_summary(plan, rows, allowed_actions)

    if args.dry_run:
        print()
        print("--dry-run: no files moved.")
        return 0

    if not plan:
        print()
        print("Nothing to do.")
        return 0

    if not args.yes:
        print()
        if not confirm("Proceed with these moves?"):
            print("Aborted.")
            return 0

    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    dest_root = root / DEPRECATE_DIR / timestamp

    moved, total_bytes = execute_moves(plan, dest_root, root)

    print()
    print("Done.")
    print(f"  Moved:        {moved} files  ({total_bytes/(1024*1024):.2f} MB)")
    print(f"  Destination:  {dest_root.relative_to(root)}")
    print()
    print("The destination tree mirrors the original relative paths, so it's")
    print("the record of what moved. Restore is a manual `Move-Item` away.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
