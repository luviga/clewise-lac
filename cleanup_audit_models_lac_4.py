#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""
MODELS_LAC_4 Cleanup Audit (REPORT ONLY - no deletion)
======================================================
Walks MODELS_LAC_4 and classifies every top-level item into:
  - KEEP: required for the v14 pipeline run
  - DELETE: legacy / superseded / will be regenerated
  - INSPECT: ambiguous, needs human eye before decision

Usage:
    py cleanup_audit_models_lac_4.py
    py cleanup_audit_models_lac_4.py --root "C:\\path\\to\\MODELS_LAC_4"

Outputs:
  - Console report grouped by classification
  - cleanup_audit_report.csv in the root (full inventory + recommendations)

This script is READ-ONLY. It will never delete or modify anything.
"""

import argparse
import csv
import sys
from pathlib import Path
from datetime import datetime


# =============================================================================
# CLASSIFICATION RULES
# =============================================================================

# Folders/files that are required for v14 pipeline run
KEEP_PATTERNS = {
    # Stage scripts (active versions only)
    "stage3_target_shares_v14.py":   "v14 active Stage 3 script",
    "stage4_generate_opt.py":         "Active Stage 4 script",
    "stage5_bau_constrained_v7.py":   "Active Stage 5 script (Costa Rica)",
    # Inputs
    "_STAGE1_OUTPUT":                 "Controller (CONTROLLER_NEW_SCENARIOS.xlsx) - REQUIRED INPUT for Stage 3",
    # Country folders
    "CostaRica":                      "Country model folder",
    "DominicanRepublic":              "Country model folder",
    "Ecuador":                        "Country model folder",
    "Guatemala":                      "Country model folder",
    "Honduras":                       "Country model folder",
    "Jamaica":                        "Country model folder",
}

# Folders that should be deleted/emptied because v14 run will repopulate them
REGENERATED_OUTPUT_FOLDERS = {
    "_STAGE3_OUTPUT":      "Stage 3 outputs - will be regenerated by v14",
    "_STAGE4_OUTPUT":      "Stage 4 outputs - will be regenerated by stage4_generate_opt.py",
    "_STAGE5_OUTPUT":      "Stage 5 outputs - will be regenerated by stage5_bau_constrained_v7.py (CR only)",
}

# Folders/files that are explicit legacy and should be deleted
LEGACY_FOLDERS = {
    "_STAGE3_SCENARIOS":   "Manual pre-pipeline staging files (Jan 2026), no longer needed",
}

# Old script versions to drop (these are everything matching stage3_target_shares_v* except v14
# and stage5_bau_constrained_v* except v7, plus stage3_recalibrate_limits_v3.py)
SUPERSEDED_SCRIPT_PREFIXES = [
    ("stage3_target_shares_v",    "v14",  "Older Stage 3 version, superseded by v14"),
    ("stage5_bau_constrained_v",  "v7",   "Older Stage 5 version, superseded by v7"),
    ("stage3_recalibrate_limits", None,   "Pre-target-shares Stage 3 approach, fully superseded"),
]

# Misc utilities - safe to keep but call out
UTILITY_FILES = {
    "folder_size_analyzer.py":      "Utility, not pipeline-critical",
    "folder_analysis.csv":           "Output of folder_size_analyzer.py, not pipeline-critical",
}


def classify(item: Path) -> tuple[str, str]:
    """
    Return (classification, reason).
    classification in {"KEEP", "DELETE", "INSPECT"}.
    """
    name = item.name

    # Country folders and required folders
    if name in KEEP_PATTERNS:
        return ("KEEP", KEEP_PATTERNS[name])

    # Output folders that will be regenerated
    if name in REGENERATED_OUTPUT_FOLDERS:
        return ("DELETE", REGENERATED_OUTPUT_FOLDERS[name] + " (delete to start clean; v14 will recreate)")

    # Explicit legacy
    if name in LEGACY_FOLDERS:
        return ("DELETE", LEGACY_FOLDERS[name])

    # Superseded script versions
    for prefix, keep_marker, reason in SUPERSEDED_SCRIPT_PREFIXES:
        if name.startswith(prefix) and name.endswith(".py"):
            if keep_marker is not None and keep_marker in name:
                # this is the active one
                return ("KEEP", f"Active version ({keep_marker})")
            return ("DELETE", reason)

    # Utility files
    if name in UTILITY_FILES:
        return ("KEEP", UTILITY_FILES[name] + " (optional, safe to keep)")

    # Markdown notes
    if name.endswith(".md"):
        return ("KEEP", "Documentation/notes")

    # Backup files
    if "backup" in name.lower() or name.endswith(".bak"):
        return ("DELETE", "Backup file - safe to remove if MODELS_LAC_2 is intact")

    # Unknown - human decision needed
    return ("INSPECT", "Unknown item - review manually before deciding")


def get_size(item: Path) -> int:
    """Total size in bytes of a file or directory."""
    if item.is_file():
        try:
            return item.stat().st_size
        except OSError:
            return 0
    total = 0
    try:
        for sub in item.rglob("*"):
            if sub.is_file():
                try:
                    total += sub.stat().st_size
                except OSError:
                    pass
    except (OSError, PermissionError):
        pass
    return total


def fmt_size(n: int) -> str:
    for unit in ["B", "KB", "MB", "GB"]:
        if n < 1024:
            return f"{n:.1f} {unit}"
        n /= 1024
    return f"{n:.1f} TB"


def get_mtime(item: Path) -> str:
    try:
        ts = item.stat().st_mtime
        return datetime.fromtimestamp(ts).strftime("%Y-%m-%d")
    except OSError:
        return "?"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", default=".",
                        help="Path to MODELS_LAC_4 root (default: current dir)")
    args = parser.parse_args()

    root = Path(args.root).resolve()
    if not root.exists():
        print(f"ERROR: root path does not exist: {root}")
        sys.exit(1)

    print("=" * 78)
    print(f"MODELS_LAC_4 CLEANUP AUDIT (READ-ONLY)")
    print(f"Root: {root}")
    print(f"Run:  {datetime.now().isoformat(timespec='seconds')}")
    print("=" * 78)

    items = sorted(root.iterdir())
    rows = []
    for item in items:
        cls, reason = classify(item)
        size = get_size(item)
        mtime = get_mtime(item)
        rows.append({
            "name": item.name,
            "type": "DIR" if item.is_dir() else "FILE",
            "size_bytes": size,
            "size_pretty": fmt_size(size),
            "modified": mtime,
            "classification": cls,
            "reason": reason,
        })

    # Group and print
    for cls in ["KEEP", "DELETE", "INSPECT"]:
        bucket = [r for r in rows if r["classification"] == cls]
        if not bucket:
            continue
        print()
        print(f"--- {cls}  ({len(bucket)} item{'s' if len(bucket) != 1 else ''}) ---")
        for r in bucket:
            print(f"  [{r['type']}] {r['name']:<45} {r['size_pretty']:>10}  {r['modified']}")
            print(f"         -> {r['reason']}")

    # Totals
    delete_size = sum(r["size_bytes"] for r in rows if r["classification"] == "DELETE")
    print()
    print("=" * 78)
    print(f"Summary: {len(rows)} top-level items")
    print(f"  KEEP:    {sum(1 for r in rows if r['classification'] == 'KEEP')}")
    print(f"  DELETE:  {sum(1 for r in rows if r['classification'] == 'DELETE')}  "
          f"(would free {fmt_size(delete_size)})")
    print(f"  INSPECT: {sum(1 for r in rows if r['classification'] == 'INSPECT')}")
    print()

    # Write CSV report
    report_path = root / "cleanup_audit_report.csv"
    with open(report_path, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=["name", "type", "size_bytes",
                                                "size_pretty", "modified",
                                                "classification", "reason"])
        writer.writeheader()
        writer.writerows(rows)
    print(f"Full inventory written to: {report_path}")
    print()
    print("NOTHING WAS DELETED. Review the report and act manually if you agree.")
    print("Reminder: confirm MODELS_LAC_2 is intact before deleting anything.")


if __name__ == "__main__":
    main()
