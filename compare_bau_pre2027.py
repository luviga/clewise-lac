#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""
Targeted comparison: BAU lower limits ≤ 2026
============================================
Compares TotalTechnologyAnnualActivityLowerLimit.csv between MODELS_LAC and
MODELS_LAC_4, but ONLY for:
  - Scenario: BAU
  - Years: 2018 through 2026 inclusive (historical/calibration period)
  - File: TotalTechnologyAnnualActivityLowerLimit.csv (the only one that
    really matters for Stage 1's share computation)

Everything else (future years, other scenarios, other parameter files) is
either regenerated by your pipeline or derived from these values, so it
doesn't need direct upstream/working comparison.

Run from MODELS_LAC_4 in Spyder. Hit F5.

Output:
  - Per-country verdict (MATCH / DIFFER) for the historical-year window
  - For DIFFER countries: which techs/years disagree and by how much
  - upstream_vs_working_pre2027.csv with full details
"""

import csv
from pathlib import Path
from collections import defaultdict


# =============================================================================
# CONFIGURATION
# =============================================================================
MODELS_LAC_PATH = r"C:\Users\luisfernando\Dropbox\2_WORK\MODELS_LAC"
MODELS_LAC_4_PATH = r"."

CUTOFF_YEAR = 2026   # inclusive — compare years 2018..2026

COUNTRY_FOLDERS = {
    "DominicanRepublic":  "DominicanRepublic/RD_ENERGY",
    "Ecuador":            "Ecuador/ECU_Energy",
    "Guatemala":          "Guatemala/GUA_ENERGY",
    "Honduras":           "Honduras/HON_ENERGY",
    "Jamaica":            "Jamaica/JAM_ENERGY",
    "CostaRica":          "CostaRica/CR_ENERGY/t1_confection",
}

TOLERANCE = 1e-4  # values within this are treated as identical


# =============================================================================
# Helpers
# =============================================================================

def load_lower_limits(path: Path, cutoff_year: int):
    """Load BAU lower-limit CSV, return dict[tech][year] = value, years <= cutoff only."""
    if not path.exists():
        return None
    data = defaultdict(dict)
    with open(path, "r", encoding="utf-8", newline="") as f:
        reader = csv.DictReader(f)
        # Find columns case-insensitively
        headers = reader.fieldnames or []
        tech_col = next((h for h in headers if h.upper() in ("TECHNOLOGY", "TECH")), None)
        year_col = next((h for h in headers if h.upper() == "YEAR"), None)
        value_col = next((h for h in headers if h.upper() in ("VALUE",)), None)
        if not all([tech_col, year_col, value_col]):
            print(f"  WARNING: could not find required columns in {path.name}")
            print(f"           found columns: {headers}")
            return None
        for row in reader:
            try:
                year = int(float(row[year_col]))
                if year > cutoff_year:
                    continue
                tech = row[tech_col]
                value = float(row[value_col]) if row[value_col] else 0.0
                data[tech][year] = value
            except (ValueError, KeyError, TypeError):
                continue
    return data


def compare_country(country, rel_path, upstream_root, working_root, cutoff_year):
    """Compare one country's BAU lower limits ≤ cutoff_year. Return findings dict."""
    rel_file = Path(rel_path) / "B1_Output_Params" / "BAU" / "TotalTechnologyAnnualActivityLowerLimit.csv"
    upstream_file = upstream_root / rel_file
    working_file = working_root / rel_file

    findings = {
        "country": country,
        "upstream_exists": upstream_file.exists(),
        "working_exists": working_file.exists(),
        "verdict": None,
        "n_techs_upstream": 0,
        "n_techs_working": 0,
        "n_techs_common": 0,
        "n_value_diffs": 0,
        "examples": [],
        "differing_rows": [],   # detailed list for CSV export
    }

    if not upstream_file.exists():
        findings["verdict"] = "UPSTREAM_FILE_MISSING"
        return findings
    if not working_file.exists():
        findings["verdict"] = "WORKING_FILE_MISSING"
        return findings

    up = load_lower_limits(upstream_file, cutoff_year)
    wo = load_lower_limits(working_file, cutoff_year)
    if up is None or wo is None:
        findings["verdict"] = "PARSE_ERROR"
        return findings

    up_techs = set(up.keys())
    wo_techs = set(wo.keys())
    common_techs = up_techs & wo_techs
    findings["n_techs_upstream"] = len(up_techs)
    findings["n_techs_working"] = len(wo_techs)
    findings["n_techs_common"] = len(common_techs)

    # Compare values for common techs
    for tech in sorted(common_techs):
        all_years = sorted(set(up[tech].keys()) | set(wo[tech].keys()))
        for year in all_years:
            up_v = up[tech].get(year, 0.0)
            wo_v = wo[tech].get(year, 0.0)
            if abs(up_v - wo_v) > TOLERANCE:
                findings["n_value_diffs"] += 1
                findings["differing_rows"].append({
                    "country": country,
                    "tech": tech,
                    "year": year,
                    "upstream_value": up_v,
                    "working_value": wo_v,
                    "absolute_diff": wo_v - up_v,
                })
                if len(findings["examples"]) < 6:
                    findings["examples"].append((tech, year, up_v, wo_v))

    # Techs in one but not the other
    only_in_upstream = up_techs - wo_techs
    only_in_working = wo_techs - up_techs
    findings["only_in_upstream"] = sorted(only_in_upstream)
    findings["only_in_working"] = sorted(only_in_working)

    # Verdict
    if findings["n_value_diffs"] == 0 and not only_in_upstream and not only_in_working:
        findings["verdict"] = "MATCH"
    elif only_in_upstream or only_in_working:
        findings["verdict"] = "TECH_SET_DIFFERS"
    else:
        findings["verdict"] = "VALUE_DIFFERS"

    return findings


def main():
    upstream_root = Path(MODELS_LAC_PATH).resolve()
    working_root = Path(MODELS_LAC_4_PATH).resolve()

    print("=" * 78)
    print(f"BAU LOWER LIMITS COMPARISON (years ≤ {CUTOFF_YEAR})")
    print("=" * 78)
    print(f"Upstream: {upstream_root}")
    print(f"Working:  {working_root}")
    print(f"Tolerance: {TOLERANCE} PJ (anything smaller = treated as identical)")
    print()

    if not upstream_root.exists():
        print(f"ERROR: upstream path does not exist: {upstream_root}")
        return
    if not working_root.exists():
        print(f"ERROR: working path does not exist: {working_root}")
        return

    all_findings = []
    all_differing_rows = []

    for country, rel_path in COUNTRY_FOLDERS.items():
        f = compare_country(country, rel_path, upstream_root, working_root, CUTOFF_YEAR)
        all_findings.append(f)
        all_differing_rows.extend(f.get("differing_rows", []))

        print(f"--- {country} ---")
        print(f"  Verdict: [{f['verdict']}]")
        if f["verdict"] == "MATCH":
            print(f"  Techs compared: {f['n_techs_common']}, years 2018-{CUTOFF_YEAR}")
            print(f"  Historical baseline is consistent between upstream and working.")
        elif f["verdict"] == "VALUE_DIFFERS":
            print(f"  Techs compared: {f['n_techs_common']}")
            print(f"  Cells with value differences: {f['n_value_diffs']}")
            print(f"  Examples (tech, year, upstream → working):")
            for tech, year, up_v, wo_v in f["examples"]:
                pct = ((wo_v - up_v) / up_v * 100) if abs(up_v) > 1e-9 else float('inf')
                print(f"    {tech:<20} {year}  {up_v:>10.4f}  →  {wo_v:>10.4f}  "
                      f"(diff {wo_v - up_v:+.4f}, {pct:+.1f}%)")
        elif f["verdict"] == "TECH_SET_DIFFERS":
            print(f"  Techs only in upstream: {f.get('only_in_upstream', [])}")
            print(f"  Techs only in working:  {f.get('only_in_working', [])}")
            print(f"  Value diffs among common techs: {f['n_value_diffs']}")
        elif f["verdict"] == "UPSTREAM_FILE_MISSING":
            print(f"  Upstream BAU lower-limit file does not exist.")
            print(f"  Cannot compare. MODELS_LAC_4 is your only source.")
        elif f["verdict"] == "WORKING_FILE_MISSING":
            print(f"  MODELS_LAC_4 BAU lower-limit file does not exist.")
            print(f"  This is a problem — Stage 1 needs this file.")
        elif f["verdict"] == "PARSE_ERROR":
            print(f"  Could not parse one of the CSVs. Manual inspection needed.")
        print()

    # Summary
    print("=" * 78)
    print("SUMMARY")
    print("=" * 78)
    verdicts = [f["verdict"] for f in all_findings]
    for v in ["MATCH", "VALUE_DIFFERS", "TECH_SET_DIFFERS", "UPSTREAM_FILE_MISSING",
              "WORKING_FILE_MISSING", "PARSE_ERROR"]:
        count = verdicts.count(v)
        if count > 0:
            print(f"  {v:<25} {count}")
    print()

    n_match = verdicts.count("MATCH")
    n_total = len(verdicts)
    if n_match == n_total:
        print(f">> All {n_total} countries' BAU historical baselines (years ≤ {CUTOFF_YEAR}) match.")
        print(">> Safe to run Stage 1 against MODELS_LAC_4 data.")
    else:
        print(f">> {n_total - n_match} country/ies show differences. Review above.")
        print(">> Decide which version is authoritative before running Stage 1.")

    # Write CSV report only if there are differences
    if all_differing_rows:
        report_path = working_root / f"upstream_vs_working_pre{CUTOFF_YEAR + 1}.csv"
        with open(report_path, "w", newline="", encoding="utf-8") as f:
            writer = csv.DictWriter(f, fieldnames=["country", "tech", "year",
                                                    "upstream_value", "working_value",
                                                    "absolute_diff"])
            writer.writeheader()
            writer.writerows(all_differing_rows)
        print(f"\nDetailed differences: {report_path.name}")
    else:
        print(f"\n(No differences — no report file written.)")


if __name__ == "__main__":
    main()
