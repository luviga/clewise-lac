import csv
import hashlib
import os

JOB = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
C = "Guatemala"


def sha(p):
    h = hashlib.sha256()
    with open(os.path.join(JOB, p), "rb") as f:
        for b in iter(lambda: f.read(1 << 20), b""):
            h.update(b)
    return h.hexdigest()


def write(name, header, rows):
    with open(os.path.join(JOB, name), "w", encoding="utf-8", newline="\n") as fh:
        w = csv.writer(fh, lineterminator="\n")
        w.writerow(header)
        w.writerows(rows)
    print(name, len(rows))


